# 14. Main pipeline
# ============================================================

def main():
    """Run the complete Phase 2 Task 4 pipeline."""

    global feature_count_global
    global X_test_global

    logger.info(
        "=" * 70
    )

    logger.info(
        "Starting Phase 2 - Task 4 MLflow experiment tracking."
    )

    pipeline_start = time.time()

    # --------------------------------------------------------
    # Configure MLflow
    # --------------------------------------------------------

    configure_mlflow()

    # --------------------------------------------------------
    # Load test data
    # --------------------------------------------------------

    test_df = load_test_data()

    (
        X_test,
        y_test,
        feature_columns,
    ) = prepare_test_features(
        test_df
    )

    feature_count_global = (
        len(feature_columns)
    )

    X_test_global = X_test

    # --------------------------------------------------------
    # Load tuning information
    # --------------------------------------------------------

    tuning_parameters = (
        load_tuning_information()
    )

    # --------------------------------------------------------
    # Track models
    # --------------------------------------------------------

    results = []

    for (
        model_name,
        model_file,
    ) in MODEL_FILES.items():

        result = track_model(
            model_name=model_name,
            model_file=model_file,
            X_test=X_test,
            y_test=y_test,
            feature_count=len(
                feature_columns
            ),
            tuning_parameters=(
                tuning_parameters
            ),
        )

        results.append(
            result
        )

    # --------------------------------------------------------
    # Save result summary
    # --------------------------------------------------------

    results_df = pd.DataFrame(
        results
    )

    results_file = (
        MODEL_RESULTS_DIR
        / "mlflow_tracking_results.csv"
    )

    results_df.to_csv(
        results_file,
        index=False,
    )

    logger.info(
        "Saved MLflow tracking summary: %s",
        results_file,
    )

    # --------------------------------------------------------
    # Save Markdown report
    # --------------------------------------------------------

    save_tracking_report(
        results_df
    )

    # --------------------------------------------------------
    # Final summary
    # --------------------------------------------------------

    total_time = (
        time.time()
        - pipeline_start
    )

    logger.info(
        "=" * 70
    )

    logger.info(
        "MLFLOW MODEL RANKING BY ROC-AUC"
    )

    logger.info(
        "\n%s",
        results_df[
            [
                "model",
                "roc_auc",
                "f1_score",
                "recall",
                "inference_ms_per_row",
            ]
        ]
        .sort_values(
            "roc_auc",
            ascending=False,
        )
        .to_string(
            index=False
        ),
    )

    logger.info(
        "MLflow database: %s",
        MLFLOW_DB,
    )

    logger.info(
        "Total tracking time: %.2f seconds",
        total_time,
    )

    logger.info(
        "Phase 2 - Task 4 completed successfully."
    )

    logger.info(
        "=" * 70
    )


# ============================================================
# 15. Entry point
# ============================================================

if __name__ == "__main__":
    main()