def load_test_data():
    """Load the untouched test dataset."""

    logger.info(
        "Loading test data..."
    )

    test_df = pd.read_csv(
        TEST_FILE
    )

    logger.info(
        "Test data shape: %s",
        test_df.shape,
    )

    return test_df


# ============================================================
# 7. Prepare test features
# ============================================================

def prepare_test_features(test_df):
    """
    Separate target from predictive features.

    Identifier columns are retained in the original dataframe
    but excluded from model prediction.
    """

    if TARGET_COLUMN not in test_df.columns:
        raise ValueError(
            f"Target column '{TARGET_COLUMN}' "
            "was not found in test data."
        )

    feature_columns = [
        column
        for column in test_df.columns
        if column not in ID_COLUMNS
        and column != TARGET_COLUMN
    ]

    if not feature_columns:
        raise ValueError(
            "No predictive features were found."
        )

    X_test = test_df[
        feature_columns
    ]

    y_test = test_df[
        TARGET_COLUMN
    ]

    logger.info(
        "Number of predictive features: %d",
        len(feature_columns),
    )

    logger.info(
        "Predictive features: %s",
        feature_columns,
    )

    logger.info(
        "Positive class rate: %.4f",
        y_test.mean(),
    )

    return (
        X_test,
        y_test,
        feature_columns,
    )


# ============================================================
# 8. Evaluate model
# ============================================================

def evaluate_model(
    model,
    X_test,
    y_test,
):
    """
    Evaluate a loaded model on the untouched test dataset.
    """

    start_time = time.perf_counter()

    predictions = model.predict(
        X_test
    )

    probabilities = model.predict_proba(
        X_test
    )[:, 1]

    inference_time = (
        time.perf_counter()
        - start_time
    )

    metrics = {
        "accuracy": accuracy_score(
            y_test,
            predictions,
        ),

        "precision": precision_score(
            y_test,
            predictions,
            zero_division=0,
        ),

        "recall": recall_score(
            y_test,
            predictions,
            zero_division=0,
        ),

        "f1_score": f1_score(
            y_test,
            predictions,
            zero_division=0,
        ),

        "roc_auc": roc_auc_score(
            y_test,
            probabilities,
        ),

        "inference_time_seconds":
            inference_time,

        "inference_ms_per_row":
            (
                inference_time
                / len(X_test)
                * 1000
            ),
    }

    return metrics


# ============================================================
# 9. Extract model parameters
# ============================================================

def get_model_parameters(model):
    """
    Extract useful model parameters for MLflow logging.

    Parameters are converted into MLflow-compatible scalar
    values where possible.
    """

    parameters = {}

    if hasattr(model, "get_params"):

        raw_parameters = (
            model.get_params()
        )

        for name, value in raw_parameters.items():

            if value is None:
                parameters[name] = "None"

            elif isinstance(
                value,
                (
                    str,
                    int,
                    float,
                    bool,
                ),
            ):
                parameters[name] = value

            else:
                parameters[name] = str(
                    value
                )

    return parameters


# ============================================================
# 10. Get model file size
# ============================================================

def get_model_size_mb(
    model_file,
):
    """Return model artifact size in megabytes."""

    if not model_file.exists():
        return 0.0

    size_bytes = (
        model_file.stat().st_size
    )

    return size_bytes / (
        1024 * 1024
    )


# ============================================================
# 11. Load tuning information
# ============================================================

def load_tuning_information():
    """
    Load hyperparameter tuning results if available.

    This information is used as additional metadata for the
    tuned Random Forest experiment.
    """

    best_parameters = {}

    parameters_file = (
        TUNING_RESULTS_DIR
        / "best_parameters.txt"
    )

    if parameters_file.exists():

        logger.info(
            "Loading tuned Random Forest parameters..."
        )

        with open(
            parameters_file,
            "r",
            encoding="utf-8",
        ) as file:

            for line in file:

                line = line.strip()

                if (
                    not line
                    or line.startswith("=")
                    or line.startswith(
                        "Phase 2"
                    )
                    or line.startswith(
                        "Best cross-validation"
                    )
                ):
                    continue

                if ":" in line:

                    parameter, value = (
                        line.split(
                            ":",
                            1,
                        )
                    )

                    best_parameters[
                        parameter.strip()
                    ] = value.strip()

    return best_parameters


