# ============================================================
# 5. Configure MLflow
# ============================================================

def configure_mlflow():
    """
    Configure MLflow using a local SQLite tracking database.

    MLflow 3.x no longer recommends the legacy filesystem
    tracking backend. SQLite provides a persistent local
    tracking store.
    """

    tracking_uri = (
        f"sqlite:///{MLFLOW_DB}"
    )

    mlflow.set_tracking_uri(
        tracking_uri
    )

    mlflow.set_experiment(
        EXPERIMENT_NAME
    )

    logger.info(
        "MLflow tracking URI: %s",
        mlflow.get_tracking_uri(),
    )

    logger.info(
        "MLflow experiment: %s",
        EXPERIMENT_NAME,
    )


