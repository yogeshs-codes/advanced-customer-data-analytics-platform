# 12. Track one model
# ============================================================

def track_model(
    model_name,
    model_file,
    X_test,
    y_test,
    feature_count,
    tuning_parameters,
):
    """
    Load, evaluate, and log one model to MLflow.
    """

    logger.info(
        "=" * 70
    )

    logger.info(
        "Tracking model: %s",
        model_name,
    )

    if not model_file.exists():

        raise FileNotFoundError(
            f"Model file not found: "
            f"{model_file}"
        )

    # --------------------------------------------------------
    # Load model
    # --------------------------------------------------------

    logger.info(
        "Loading model: %s",
        model_file,
    )

    model = joblib.load(
        model_file
    )

    # --------------------------------------------------------
    # Evaluate model
    # --------------------------------------------------------

    evaluation_start = time.perf_counter()

    metrics = evaluate_model(
        model,
        X_test,
        y_test,
    )

    evaluation_time = (
        time.perf_counter()
        - evaluation_start
    )

    # --------------------------------------------------------
    # Model parameters
    # --------------------------------------------------------

    parameters = (
        get_model_parameters(
            model
        )
    )

    # --------------------------------------------------------
    # Model metadata
    # --------------------------------------------------------

    model_size_mb = (
        get_model_size_mb(
            model_file
        )
    )

    parameters[
        "model_name"
    ] = model_name

    parameters[
        "feature_count"
    ] = feature_count

    parameters[
        "random_state"
    ] = RANDOM_STATE

    parameters[
        "test_rows"
    ] = len(X_test)

    parameters[
        "positive_class_rate"
    ] = round(
        float(y_test.mean()),
        6,
    )

    if model_name == (
        "tuned_random_forest"
    ):

        parameters[
            "tuning_source"
        ] = "Phase 2 Task 2"

        for (
            parameter,
            value,
        ) in tuning_parameters.items():

            key = (
                f"tuned_{parameter}"
            )

            parameters[key] = value

    # --------------------------------------------------------
    # Start MLflow run
    # --------------------------------------------------------

    with mlflow.start_run(
        run_name=model_name
    ) as run:

        logger.info(
            "MLflow run ID: %s",
            run.info.run_id,
        )

        # ----------------------------------------------------
        # Tags
        # ----------------------------------------------------

        mlflow.set_tag(
            "phase",
            "Phase 2",
        )

        mlflow.set_tag(
            "task",
            "Task 4",
        )

        mlflow.set_tag(
            "project",
            "Customer Demand Analysis",
        )

        mlflow.set_tag(
            "model_type",
            model_name,
        )

        if model_name == (
            "tuned_random_forest"
        ):

            mlflow.set_tag(
                "tuning",
                "RandomizedSearchCV",
            )

        else:

            mlflow.set_tag(
                "tuning",
                "baseline",
            )

        # ----------------------------------------------------
        # Parameters
        # ----------------------------------------------------

        for (
            parameter,
            value,
        ) in parameters.items():

            try:

                mlflow.log_param(
                    parameter,
                    value,
                )

            except Exception as exc:

                logger.warning(
                    "Could not log parameter "
                    "%s: %s",
                    parameter,
                    exc,
                )

        # ----------------------------------------------------
        # Metrics
        # ----------------------------------------------------

        mlflow.log_metric(
            "accuracy",
            float(metrics["accuracy"]),
        )

        mlflow.log_metric(
            "precision",
            float(metrics["precision"]),
        )

        mlflow.log_metric(
            "recall",
            float(metrics["recall"]),
        )

        mlflow.log_metric(
            "f1_score",
            float(metrics["f1_score"]),
        )

        mlflow.log_metric(
            "roc_auc",
            float(metrics["roc_auc"]),
        )

        mlflow.log_metric(
            "inference_time_seconds",
            float(
                metrics[
                    "inference_time_seconds"
                ]
            ),
        )

        mlflow.log_metric(
            "inference_ms_per_row",
            float(
                metrics[
                    "inference_ms_per_row"
                ]
            ),
        )

        mlflow.log_metric(
            "model_size_mb",
            float(model_size_mb),
        )

        mlflow.log_metric(
            "evaluation_time_seconds",
            float(evaluation_time),
        )

        # ----------------------------------------------------
        # Model artifact
        # ----------------------------------------------------

        mlflow.log_artifact(
            str(model_file),
            artifact_path="model",
        )

        # ----------------------------------------------------
        # Existing result artifacts
        # ----------------------------------------------------

        if MODEL_RESULTS_DIR.exists():

            architecture_csv = (
                MODEL_RESULTS_DIR
                / "architecture_comparison.csv"
            )

            if architecture_csv.exists():

                mlflow.log_artifact(
                    str(architecture_csv),
                    artifact_path=(
                        "existing_results"
                    ),
                )

        if model_name == (
            "tuned_random_forest"
        ):

            tuning_metrics_file = (
                TUNING_RESULTS_DIR
                / "tuning_metrics.csv"
            )

            if tuning_metrics_file.exists():

                mlflow.log_artifact(
                    str(tuning_metrics_file),
                    artifact_path=(
                        "tuning_results"
                    ),
                )

            best_parameters_file = (
                TUNING_RESULTS_DIR
                / "best_parameters.txt"
            )

            if best_parameters_file.exists():

                mlflow.log_artifact(
                    str(best_parameters_file),
                    artifact_path=(
                        "tuning_results"
                    ),
                )

        # ----------------------------------------------------
        # Save model using MLflow
        # ----------------------------------------------------

        try:

            mlflow.sklearn.log_model(
                sk_model=model,
                name="model",
            )

        except Exception as exc:

            logger.warning(
                "MLflow sklearn model logging "
                "failed for %s: %s",
                model_name,
                exc,
            )

        # ----------------------------------------------------
        # Summary
        # ----------------------------------------------------

        logger.info(
            "Accuracy: %.6f",
            metrics["accuracy"],
        )

        logger.info(
            "Precision: %.6f",
            metrics["precision"],
        )

        logger.info(
            "Recall: %.6f",
            metrics["recall"],
        )

        logger.info(
            "F1 Score: %.6f",
            metrics["f1_score"],
        )

        logger.info(
            "ROC-AUC: %.6f",
            metrics["roc_auc"],
        )

        logger.info(
            "Inference time: %.4f seconds",
            metrics[
                "inference_time_seconds"
            ],
        )

        logger.info(
            "Inference latency: %.6f ms/row",
            metrics[
                "inference_ms_per_row"
            ],
        )

        logger.info(
            "Model size: %.4f MB",
            model_size_mb,
        )

        logger.info(
            "Completed MLflow run: %s",
            run.info.run_id,
        )

        return {
            "model": model_name,
            "run_id": run.info.run_id,
            "accuracy": metrics["accuracy"],
            "precision": metrics["precision"],
            "recall": metrics["recall"],
            "f1_score": metrics["f1_score"],
            "roc_auc": metrics["roc_auc"],
            "inference_time_seconds":
                metrics[
                    "inference_time_seconds"
                ],
            "inference_ms_per_row":
                metrics[
                    "inference_ms_per_row"
                ],
            "model_size_mb":
                model_size_mb,
        }


